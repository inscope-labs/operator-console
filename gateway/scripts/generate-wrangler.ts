/**
 * Generate wrangler.toml from the checked-in template.
 * Spec §18.6 — the file is generated and refused if hand-edited.
 *
 * Usage: tsx scripts/generate-wrangler.ts [--env staging|production]
 *
 * The deploy gate must compare the working tree wrangler.toml against
 * a fresh generation and fail if they differ.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const TEMPLATE = resolve(ROOT, 'wrangler.toml.template');
const OUTPUT = resolve(ROOT, 'wrangler.toml');

function main(): void {
  const envArg = process.argv.find((a) => a.startsWith('--env='))?.split('=')[1]
    ?? process.argv[process.argv.indexOf('--env') + 1]
    ?? 'staging';

  if (!existsSync(TEMPLATE)) {
    console.error('wrangler.toml.template not found');
    process.exit(1);
  }

  const template = readFileSync(TEMPLATE, 'utf8');

  // Minimal generation: substitute environment name and add a generation stamp.
  // Full implementation will inject account_id, zone, secrets bindings, etc.
  const generated =
    `# Generated by scripts/generate-wrangler.ts — DO NOT EDIT BY HAND\n` +
    `# env=${envArg} generatedAt=${new Date().toISOString()}\n` +
    template.replace(
      'name = "cbridge"',
      `name = "cbridge-${envArg}"`
    );

  writeFileSync(OUTPUT, generated, 'utf8');
  console.log(`wrote ${OUTPUT} for env=${envArg}`);
}

/**
 * Check mode: exit non-zero if the on-disk wrangler.toml does not match
 * a fresh generation. Used as a deploy gate.
 */
export function assertGeneratedMatches(env: string = 'staging'): void {
  // TODO: re-generate into a temp buffer and diff against OUTPUT.
  // For now only ensure the file declares itself as generated.
  if (!existsSync(OUTPUT)) {
    throw new Error('wrangler.toml missing — run generate-wrangler first');
  }
  const content = readFileSync(OUTPUT, 'utf8');
  if (!content.includes('DO NOT EDIT BY HAND')) {
    throw new Error(
      'wrangler.toml does not carry the generation marker — possible hand edit'
    );
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
